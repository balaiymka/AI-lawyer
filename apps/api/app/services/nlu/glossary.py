_COMPILED = [(re.compile(p, re.I), terms) for p, terms in GLOSSARY]


def expand_query(text: str) -> str:
    """Возвращает дополнительные юридические термины для запроса (пустая строка, если ничего не найдено)."""
    seen: list[str] = []
    for pattern, terms in _COMPILED:
        if pattern.search(text) and terms not in seen:
            seen.append(terms)
    return " ".join(seen)
