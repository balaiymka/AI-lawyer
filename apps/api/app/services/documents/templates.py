def _sender(lang: Lang, v: V) -> list[str]:
    if lang == "ru":
        return [f"от {v.get_('applicant_name')},", f"собственника квартиры № {v.get_('apartment')},",
                f"адрес: {v.get_('building_address')}", f"тел.: {v.get_('phone')}"]
    return [f"{v.get_('building_address')} мекенжайы бойынша", f"№ {v.get_('apartment')} пәтердің меншік иесі",
            f"{v.get_('applicant_name')}", f"тел.: {v.get_('phone')}"]


def _osi_to(lang: Lang, v: V) -> list[str]:
    if lang == "ru":
        return [f"Председателю {v.get_('osi_name')}", v.get_("chair_name")]
    return [f"{v.get_('osi_name')} төрағасына", v.get_("chair_name")]


def _sign(lang: Lang, v: V) -> list[str]:
    d = v.date_("doc_date")
    return ([f"Дата: {d}", f"Подпись: ________ / {v.get_('applicant_name')} /"] if lang == "ru"
            else [f"Күні: {d}", f"Қолы: ________ / {v.get_('applicant_name')} /"])


