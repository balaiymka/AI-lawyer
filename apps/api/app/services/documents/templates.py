"""Шаблоны документов (Document Builder без ИИ): поля формы + сборка текста на ru/kk.

Ссылки на нормы — только на пункты, сверенные с текстом Закона РК «О жилищных отношениях» в базе:
ст. 39 п. 4 (акт об аварии), ст. 42 п. 17 (копия протокола — 5 рабочих дней),
ст. 46 п. 1 (ежемесячный отчёт — до 20-го числа, годовой — до 1 апреля),
ст. 10-9 п. 3 (жилищная инспекция: контроль отчётов, предписания).
В претензии и иске нормы ГК/ГПК намеренно без номеров: шаблон не знает обстоятельств дела.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Callable, Literal

Lang = Literal["ru", "kk"]
BLANK = "________"


@dataclass
class Field:
    key: str
    ru: str
    kk: str
    type: Literal["text", "textarea", "date", "number", "select"] = "text"
    required: bool = False
    options: list[tuple[str, str, str]] = field(default_factory=list)  # (value, ru, kk)
    hint_ru: str = ""
    hint_kk: str = ""

    def public(self, lang: Lang) -> dict:
        return {"key": self.key, "label": self.ru if lang == "ru" else self.kk, "type": self.type,
                "required": self.required, "hint": self.hint_ru if lang == "ru" else self.hint_kk,
                "options": [{"value": v, "label": r if lang == "ru" else k} for v, r, k in self.options]}


@dataclass
class Doc:
    title: str
    to: list[str]
    sender: list[str]
    body: list[str]
    requests_intro: str = ""
    requests: list[str] = field(default_factory=list)
    attachments_title: str = ""
    attachments: list[str] = field(default_factory=list)
    signature: list[str] = field(default_factory=list)
    note: str = ""  # подсказка для пользователя, в документ не печатается


@dataclass
class Template:
    code: str
    title_ru: str
    title_kk: str
    desc_ru: str
    desc_kk: str
    basis: list[str]  # пути пунктов ЗЖО
    fields: list[Field]
    render: Callable[[Lang, "V"], Doc]
    category: str

    def public(self, lang: Lang) -> dict:
        return {"code": self.code, "title": self.title_ru if lang == "ru" else self.title_kk,
                "description": self.desc_ru if lang == "ru" else self.desc_kk, "basis": self.basis,
                "category": self.category, "fields": [f.public(lang) for f in self.fields]}


class V(dict):
    """Значения формы: пустое поле печатается как линия для заполнения от руки."""

    def __missing__(self, key):
        return BLANK

    def get_(self, key: str) -> str:
        v = str(self.get(key) or "").strip()
        return v or BLANK

    def date_(self, key: str) -> str:
        v = str(self.get(key) or "").strip()
        if not v:
            return BLANK
        try:
            return date.fromisoformat(v).strftime("%d.%m.%Y")
        except ValueError:
            return v


